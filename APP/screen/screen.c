//屏幕3
static void screen_name2(void)
{
    OLED_ShowString_F8X16(0, 0, (uint8_t*)"Counter");
    sprintf(buf, "%lu", (unsigned long)counter);
    OLED_ShowString_F8X16(2, 6, (uint8_t*)buf);
}

static void draw_screen(void)
{
    OLED_CLS();  // 清屏

    //选择要显示的屏幕内容
    switch (current_screen)
    {
        case SCREEN_MAIN:
            screen_main();
            break;
        case SCREEN_name1:
            screen_name1();
            break;
        case SCREEN_name2:
            screen_name2();
            break;
        default:
            break;
    }
}

void Screen_Init(void)   
{
    draw_screen(); 
}

void Screen_Switch(void)
{
    current_screen = (screen_id_t)(current_screen + 1) % SCREEN_COUNT;  // 循环切换屏幕
    draw_screen();  // 绘制当前屏幕内容
}

void Screen_Update(void)
{
    static uint32_t last = 0;
    if (current_screen == SCREEN_name2 && HAL_GetTick() - last >= 200) {
        last = HAL_GetTick();
        counter++;   // 计数器 +1（改的是数字，不是当前屏号！）
        screen_name2();
    }
}













